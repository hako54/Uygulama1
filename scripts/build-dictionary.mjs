// Generates src/dictionary.ts: every 5-letter word the game accepts as a guess.
// Sources (both MIT): wordle-tr-dictionary (TDK based) and an-array-of-english-words (Letterpress).
// Run with: npm run build:dictionary
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const tr = require('wordle-tr-dictionary/data/generated/words.json').accepted_words;
const en = require('an-array-of-english-words');

const ALPHABET = {
  tr: /^[ABCÇDEFGĞHIİJKLMNOÖPRSŞTUÜVYZ]{5}$/u,
  en: /^[A-Z]{5}$/,
};

function clean(words, lang) {
  const up = (w) => (lang === 'tr' ? w.toLocaleUpperCase('tr-TR') : w.toUpperCase());
  return [...new Set(words.map(up))].filter((w) => ALPHABET[lang].test(w)).sort();
}

const lists = { tr: clean(tr, 'tr'), en: clean(en, 'en') };

const body = Object.entries(lists)
  .map(([lang, words]) => `  ${lang}: '${words.join(' ')}',`)
  .join('\n');

writeFileSync(
  new URL('../src/dictionary.ts', import.meta.url),
  `// Generated by scripts/build-dictionary.mjs — do not edit by hand.\n` +
    `// Space-separated so the bundle stays small; split into a Set on first use.\n` +
    `export const DICTIONARY = {\n${body}\n};\n`,
);

for (const [lang, words] of Object.entries(lists)) console.log(`${lang}: ${words.length} words`);
