// Generates the word data the game ships with:
//  - src/dictionary.ts: every 5-letter word accepted as a guess
//  - src/words.ts: the daily answers
// Hand-picked answers and exclusions live in scripts/words/<lang>.{curated,exclude}.txt.
// Run with: npm run build:words
//
// Once the app is published, only APPEND new answers: the daily word is picked from a fixed
// shuffle of this list, so changing existing entries changes past and future puzzles.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8');
const words = (s) => s.split(/\s+/).filter(Boolean);
const bip39 = (lang) => require(`bip39/src/wordlists/${lang}.json`);

// Accents are dropped so players only need the letters on the keyboard; Spanish keeps Ñ and
// Turkish keeps its own letters. German spells umlauts out (Ä → AE) like crosswords do.
const stripMarks = (w) => w.normalize('NFD').replace(/\p{M}/gu, '').normalize('NFC');
const NORMALIZE = {
  tr: (w) => w.toLocaleUpperCase('tr-TR'),
  en: (w) => w.toUpperCase(),
  es: (w) => stripMarks(w.normalize('NFC').toUpperCase().replace(/Ñ/g, '\0')).replace(/\0/g, 'Ñ'),
  pt: (w) => stripMarks(w.toUpperCase()),
  fr: (w) => stripMarks(w.toUpperCase().replace(/Œ/g, 'OE').replace(/Æ/g, 'AE')),
  de: (w) =>
    w.toUpperCase().replace(/Ä/g, 'AE').replace(/Ö/g, 'OE').replace(/Ü/g, 'UE').replace(/ß/g, 'SS'),
};

const ALPHABET = {
  tr: /^[ABCÇDEFGĞHIİJKLMNOÖPRSŞTUÜVYZ]{5}$/u,
  en: /^[A-Z]{5}$/,
  es: /^[A-ZÑ]{5}$/u,
  pt: /^[A-Z]{5}$/,
  fr: /^[A-Z]{5}$/,
  de: /^[A-Z]{5}$/,
};

// SCOWL lists inflections separately; keep only the most common base forms.
function commonEnglish() {
  const scowl = require('wordlist-english');
  const all = new Set(
    Object.keys(scowl)
      .filter((k) => /^english(\/american)?\/\d+$/.test(k))
      .flatMap((k) => scowl[k]),
  );
  const common = ['english/10', 'english/20', 'english/american/10', 'english/american/20'].flatMap(
    (k) => scowl[k],
  );
  const inflected = (w) =>
    (w.endsWith('s') && (all.has(w.slice(0, -1)) || (w.endsWith('es') && all.has(w.slice(0, -2))))) ||
    (w.endsWith('ed') && (all.has(w.slice(0, -2)) || all.has(w.slice(0, -1)))) ||
    w.endsWith('ing');
  return common.filter((w) => /^[a-z]{5}$/.test(w) && !inflected(w));
}

const tdk = require('wordle-tr-dictionary/data/generated/words.json');

// guesses: dictionary sources; answers: extra answer sources besides the curated file.
const SOURCES = {
  tr: { guesses: [tdk.accepted_words], answers: tdk.target_words },
  en: { guesses: [require('an-array-of-english-words'), commonEnglish()], answers: commonEnglish() },
  es: { guesses: [require('an-array-of-spanish-words')], answers: bip39('spanish') },
  pt: { guesses: [require('an-array-of-portuguese-words')], answers: bip39('portuguese') },
  fr: { guesses: [require('an-array-of-french-words')], answers: bip39('french') },
  de: { guesses: [require('all-the-german-words-ascii')], answers: [] },
};

const clean = (list, lang) =>
  [...new Set(list.map(NORMALIZE[lang]))].filter((w) => ALPHABET[lang].test(w)).sort();

const dictionary = {};
const daily = {};
for (const [lang, src] of Object.entries(SOURCES)) {
  dictionary[lang] = clean(src.guesses.flat(), lang);
  const known = new Set(dictionary[lang]);
  const exclude = new Set(clean(words(read(`./words/${lang}.exclude.txt`)), lang));
  const curated = clean(words(read(`./words/${lang}.curated.txt`)), lang);
  const unknown = curated.filter((w) => !known.has(w));
  if (unknown.length) console.warn(`${lang}: not in dictionary, skipped: ${unknown.join(' ')}`);
  daily[lang] = clean([...curated.filter((w) => known.has(w)), ...src.answers], lang).filter(
    (w) => !exclude.has(w) && known.has(w),
  );
}

const header = `// Generated by scripts/build-words.mjs — do not edit by hand.\n`;
const body = (lists, suffix) =>
  Object.entries(lists)
    .map(([lang, list]) => `  ${lang}: '${list.join(' ')}'${suffix},`)
    .join('\n');

writeFileSync(
  new URL('../src/dictionary.ts', import.meta.url),
  header +
    `// Space-separated so the bundle stays small; split into a Set on first use.\n` +
    `export const DICTIONARY = {\n${body(dictionary, '')}\n};\n`,
);
writeFileSync(
  new URL('../src/words.ts', import.meta.url),
  header + `export const WORDS = {\n${body(daily, ".split(' ')")}\n};\n`,
);

for (const lang of Object.keys(SOURCES)) {
  console.log(`${lang}: ${dictionary[lang].length} guesses, ${daily[lang].length} answers`);
}
